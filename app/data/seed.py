def _horario(de="09:00", a="19:00", dias=None):
    dias = set(dias or ["lunes", "martes", "miercoles", "jueves", "viernes", "sabado"])
    return {
        dia: {"abre": dia in dias, "de": de, "a": a}
        for dia in ["lunes", "martes", "miercoles", "jueves", "viernes", "sabado", "domingo"]
    }


